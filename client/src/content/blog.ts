export function getBlogPost(slug: string) {
  return blogPosts.find(post => post.slug === slug);
}

export function getRelatedPosts(currentSlug: string, limit = 3) {
  const current = getBlogPost(currentSlug);
  const sameCategory = blogPosts.filter(post => post.slug !== currentSlug && post.category === current?.category);
  const others = blogPosts.filter(post => post.slug !== currentSlug && post.category !== current?.category);
  return [...sameCategory, ...others].slice(0, limit);
}

export function getBlogPostFromPath(path: string) {
  const match = path.match(/^\/blog\/([^/]+)$/);
  return match ? getBlogPost(match[1]) : undefined;
}

